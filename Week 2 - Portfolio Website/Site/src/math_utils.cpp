/**
 * @file math_utils.cpp
 * @brief A simple utility file for basic math operations.
 */
class MathUtils {
public:
    /**
     * @brief Adds two integers.
     * @param a First integer.
     * @param b Second integer.
     * @return Sum of a and b.
     */
    int add(int a, int b) { return a + b; }
};
